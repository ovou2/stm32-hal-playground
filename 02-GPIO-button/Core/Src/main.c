/**
  * @brief  读按键，返回 0=没按 / 1=KEY1 被按 / 2=KEY2 被按
  * @note   轮询 + 延时消抖。松手才返回，所以按住不放只会算一次。
  *         缺点：等松手的 while 是阻塞的，按住不放会卡住主循环。
  */
uint8_t Key_getnum(void)
{
	if (HAL_GPIO_ReadPin(KEY1_GPIO_Port, KEY1_Pin) == GPIO_PIN_RESET)
	{
		HAL_Delay(20);                                              /* 越过抖动区 */
		if (HAL_GPIO_ReadPin(KEY1_GPIO_Port, KEY1_Pin) == GPIO_PIN_RESET)   /* 二次确认 */
		{
			while (HAL_GPIO_ReadPin(KEY1_GPIO_Port, KEY1_Pin) == GPIO_PIN_RESET);  /* 等松手 */
			return 1;
		}
	}
	else if (HAL_GPIO_ReadPin(KEY2_GPIO_Port, KEY2_Pin) == GPIO_PIN_RESET)
	{
		HAL_Delay(20);
		if (HAL_GPIO_ReadPin(KEY2_GPIO_Port, KEY2_Pin) == GPIO_PIN_RESET)
		{
			while (HAL_GPIO_ReadPin(KEY2_GPIO_Port, KEY2_Pin) == GPIO_PIN_RESET);
			return 2;
		}
	}
	return 0;
}

/* HAL 已经提供了 HAL_GPIO_TogglePin()（内部：读一次 ODR → 一次写 BSRR），
   不需要自己写"读 + 判断 + 写"。这两个薄封装只是让主循环读起来更清楚。 */
void LED1_toggle(void)
{
	HAL_GPIO_TogglePin(LED1_GPIO_Port, LED1_Pin);
}

void LED2_toggle(void)
{
	HAL_GPIO_TogglePin(LED2_GPIO_Port, LED2_Pin);
}

